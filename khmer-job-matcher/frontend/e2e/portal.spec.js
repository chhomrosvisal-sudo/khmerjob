test('admin aliases, confirmation cancellation and notification filters work in the browser', async ({ page }) => {
  const updates = []
  page.on('request', request => { if (request.method() === 'PATCH') updates.push(request.url()) })
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(process.env.E2E_ADMIN_EMAIL)
  await page.getByLabel('Password', { exact: true }).fill(process.env.E2E_ADMIN_PASSWORD)
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Recruitment overview' })).toBeVisible()
  await page.goto('/admin/jobs')
  await expect(page).toHaveURL(/\/dashboard\/jobs$/)
  const archive = page.getByRole('button', { name: 'Archive listing', exact: true }).first()
  await archive.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(archive).toBeFocused()
  expect(updates).toEqual([])
  await page.goto('/admin/notifications')
  await expect(page).toHaveURL(/\/dashboard\/notifications$/)
  await page.getByRole('checkbox', { name: 'Unread only' }).check()
  await expect(page.getByText('No notifications yet. Application updates will appear here.')).toBeVisible()
  await page.getByRole('button', { name: 'Mark all as read' }).click()
  await expect(page.getByRole('button', { name: 'Mark all as read' })).toBeEnabled()
  await page.setViewportSize({ width: 360, height: 800 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('admin dashboard keeps its session and supports desktop, tablet and mobile navigation', async ({ page }, testInfo) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(process.env.E2E_ADMIN_EMAIL)
  await page.getByLabel('Password', { exact: true }).fill(process.env.E2E_ADMIN_PASSWORD)
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Recruitment overview' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Recruitment overview' })).toBeVisible()
  await expect(page).toHaveURL(/\/dashboard$/)
  for (const width of [1440, 768, 360]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`admin-overview-${width}.png`), fullPage: true })
  }
  const toggle = page.getByRole('button', { name: 'Toggle navigation' })
  await toggle.click()
  const nav = page.getByRole('navigation', { name: 'Main navigation' })
  await expect(nav.getByRole('link', { name: 'Applications', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(toggle).toBeFocused()
  await toggle.click()
  await nav.getByRole('link', { name: 'Applications', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard\/applications$/)
  await expect(page.getByRole('table')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.reload()
  await expect(page.getByRole('table')).toBeVisible()
  await expect(page).toHaveURL(/\/dashboard\/applications$/)
  await toggle.click()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL(/\/login\?next=/)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Login', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
