test('job seeker registers from a job, logs in, returns, applies, and sees their application', async ({ page }) => {
  await page.goto('/jobs')
  await page.getByRole('link', { name: 'View details' }).first().click()
  await expect(page).toHaveURL(/\/jobs\/\d+$/)
  const jobPath = new URL(page.url()).pathname
  await page.getByRole('link', { name: 'Login to apply' }).click()
  await page.getByRole('link', { name: 'Sign Up', exact: true }).click()
  await page.getByLabel('Name').fill('Sokha Browser Test')
  const email = `browser-${Date.now()}@example.com`
  const password = 'Browser-test-password-123!'
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByLabel('Confirm Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Create Account', exact: true }).click()
  await expect(page).toHaveURL(/\/login\?next=/)
  await expect(page.getByText('Account created. Log in to find a job.')).toBeVisible()
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`${jobPath.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`))
  await expect(page.getByRole('button', { name: 'Submit demo application' })).toBeVisible()
  await page.getByRole('link', { name: 'My Account', exact: true }).click()
  await page.getByRole('link', { name: 'Resume upload' }).click()
  await page.getByLabel('Choose your resume').setInputFiles({ name: 'browser-cv.txt', mimeType: 'text/plain', buffer: Buffer.from('Skills: Python, React, HTML and CSS.') })
  await page.getByRole('button', { name: 'Upload resume', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'browser-cv.txt' })).toBeVisible()
  await page.goto(jobPath)
  await page.getByRole('button', { name: 'Submit demo application' }).click()
  await expect(page.getByRole('heading', { name: 'Application recorded' })).toBeVisible()
  await page.getByRole('link', { name: 'View my applications' }).click()
  await expect(page.getByText('submitted', { exact: true })).toBeVisible()
  await page.evaluate(() => { history.pushState({}, '', '/dashboard'); window.dispatchEvent(new PopStateEvent('popstate')) })
  await expect(page).toHaveURL(/\/jobs$/)
})

