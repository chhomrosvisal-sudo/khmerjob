import { test, expect } from '@playwright/test'

test('guest dashboard requires login and mobile homepage has no horizontal overflow', async ({ page }) => {
  await page.goto('/dashboard')
  await expect(page).toHaveURL(/\/login\?next=/)
  await page.setViewportSize({ width: 360, height: 800 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Find Your Dream Job in Cambodia' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Open menu' }).click()
  await expect(page.getByRole('navigation', { name: 'Website navigation' })).toBeVisible()
})

test('job seeker registers, uploads a private resume, applies, and sees their application', async ({ page }) => {
  await page.goto('/register')
  await page.getByLabel('First Name').fill('Sokha')
  await page.getByLabel('Last Name').fill('Browser Test')
  await page.getByLabel('Email', { exact: true }).fill(`browser-${Date.now()}@example.com`)
  await page.getByLabel('Password', { exact: true }).fill('Browser-test-password-123!')
  await page.getByLabel('Confirm Password', { exact: true }).fill('Browser-test-password-123!')
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Create Account', exact: true }).click()
  await expect(page).toHaveURL(/\/jobs$/)
  await page.getByRole('link', { name: 'My Account', exact: true }).click()
  await page.getByRole('link', { name: 'Resume upload' }).click()
  await page.getByLabel('Choose your resume').setInputFiles({ name: 'browser-cv.txt', mimeType: 'text/plain', buffer: Buffer.from('Skills: Python, React, HTML and CSS.') })
  await page.getByRole('button', { name: 'Upload resume', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'browser-cv.txt' })).toBeVisible()
  await page.getByRole('link', { name: 'Find Jobs', exact: true }).click()
  await page.getByRole('link', { name: 'View details' }).first().click()
  await page.getByRole('button', { name: 'Submit demo application' }).click()
  await expect(page.getByRole('heading', { name: 'Application recorded' })).toBeVisible()
  await page.getByRole('link', { name: 'View my applications' }).click()
  await expect(page.getByText('submitted', { exact: true })).toBeVisible()
  await page.evaluate(() => { history.pushState({}, '', '/dashboard'); window.dispatchEvent(new PopStateEvent('popstate')) })
  await expect(page).toHaveURL(/\/jobs$/)
})

test('administrator login opens the real management dashboard', async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(process.env.E2E_ADMIN_EMAIL)
  await page.getByLabel('Password', { exact: true }).fill(process.env.E2E_ADMIN_PASSWORD)
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
  await expect(page.getByRole('heading', { name: 'Recruitment overview' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Approve employer' })).toHaveCount(0)
})
