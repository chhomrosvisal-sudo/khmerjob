import fs from 'node:fs'

const input = new URL('../src/i18n/translations.tsv', import.meta.url)
const output = new URL('../src/i18n/messages.js', import.meta.url)
const messages = {}
for (const [index, line] of fs.readFileSync(input, 'utf8').split(/\r?\n/).entries()) {
  if (!line.trim() || line.startsWith('#')) continue
  const fields = line.split('\t')
  if (fields.length !== 3 || fields.some(field => !field.trim())) throw new Error(`Invalid translation row ${index + 1}`)
  const [aliases, km, zh] = fields
  for (const key of aliases.split('|')) {
    if (messages[key] && (messages[key].km !== km || messages[key].zh !== zh)) throw new Error(`Conflicting translation: ${key}`)
    messages[key] = { km, zh }
  }
}
fs.writeFileSync(output, '// Generated by scripts/build-translations.mjs from human-authored translations.tsv.\nexport const messages = ' + JSON.stringify(messages, null, 2) + '\n')
console.log(`Built ${Object.keys(messages).length} Khmer/Chinese messages.`)
